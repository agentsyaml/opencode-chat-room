// Build the distributable Feishu adapter as one typed TypeScript file.
//
// Bundlers erase type annotations, so a bundled .ts is JavaScript with a TypeScript
// extension. This script concatenates the typed source modules instead, keeping
// interfaces, type aliases, generics, and parameter annotations intact. The output
// has no relative imports and runs directly under Node's type stripping.
import { promises as fs } from "node:fs";
import path from "node:path";

type Module = { file: string; rename?: Record<string, string> };

const ROOT = path.resolve(import.meta.dir, "..");
const MODULES: Module[] = [
  { file: "packages/chat-room-channeld/src/protocol.ts" },
  { file: "packages/chat-room-channeld/src/framing.ts" },
  { file: "plugins/feishu/src/feishu-card.ts" },
  { file: "plugins/feishu/src/feishu-ws-frames.ts" },
  { file: "plugins/feishu/src/feishu-inbound.ts", rename: { isRecord: "inboundIsRecord" } },
  {
    file: "plugins/feishu/src/feishu-send.ts",
    rename: {
      DEFAULT_BASE_URL: "SEND_DEFAULT_BASE_URL",
      DEFAULT_TIMEOUT_MS: "SEND_DEFAULT_TIMEOUT_MS",
      isRecord: "sendIsRecord",
      logLine: "sendLogLine",
    },
  },
  { file: "plugins/feishu/src/feishu-live.ts", rename: { isRecord: "liveIsRecord" } },
  { file: "plugins/feishu/src/feishu-adapter.ts" },
];
const OUTPUT = "plugins/feishu/dist/feishu-adapter.ts";

function stripRelativeImports(source: string): string {
  const lines = source.split("\n");
  const kept: string[] = [];
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index]!;
    const trimmed = line.trimStart();
    const isImport = trimmed.startsWith("import ");
    const isReExport = trimmed.startsWith("export {") && trimmed.includes(" from ");
    if (!isImport && !isReExport) {
      kept.push(line);
      continue;
    }
    let block = line;
    while (!block.trimEnd().endsWith(";") && index + 1 < lines.length) {
      index++;
      block += `\n${lines[index]!}`;
    }
    if (/\bfrom\s+["']\.\.?\//.test(block)) continue;
    kept.push(block);
  }
  return kept.join("\n");
}

function renameIdentifier(source: string, from: string, to: string): string {
  return source.replace(new RegExp(`\\b${from}\\b`, "g"), to);
}

function declarations(source: string): Map<string, number> {
  const found = new Map<string, number>();
  const pattern = /^(?:export\s+)?(?:async\s+)?(?:function|class|interface|type|const|let|enum)\s+([A-Za-z_$][\w$]*)/gm;
  for (const match of source.matchAll(pattern)) {
    found.set(match[1]!, (found.get(match[1]!) ?? 0) + 1);
  }
  return found;
}

async function main(): Promise<void> {
  const sections: string[] = [
    "// Generated by scripts/build-feishu-adapter.ts from plugins/feishu/src and the",
    "// shared channeld protocol/framing sources. Do not edit by hand.",
    "",
  ];
  const seenImports = new Set<string>();
  for (const module of MODULES) {
    let source = await fs.readFile(path.join(ROOT, module.file), "utf8");
    for (const [from, to] of Object.entries(module.rename ?? {})) source = renameIdentifier(source, from, to);
    source = stripRelativeImports(source);
    const importLines = source.split("\n").filter((line) => line.trimStart().startsWith("import "));
    for (const line of importLines) {
      const normalized = line.trim();
      if (seenImports.has(normalized)) source = source.replace(`${line}\n`, "");
      else seenImports.add(normalized);
    }
    sections.push(`// ---- ${module.file} ----`, source.trim(), "");
  }
  const output = `${sections.join("\n").trim()}\n`;
  if (/\bfrom\s+["']\.\.?\//.test(output)) throw new Error("generated adapter still has relative imports");

  const all = declarations(output);
  const duplicates = [...all].filter(([, count]) => count > 1).map(([name]) => name);
  if (duplicates.length) throw new Error(`duplicate top-level declarations: ${duplicates.join(", ")}`);

  new Bun.Transpiler({ loader: "ts" }).transformSync(output);
  await fs.mkdir(path.join(ROOT, path.dirname(OUTPUT)), { recursive: true });
  await fs.writeFile(path.join(ROOT, OUTPUT), output);
  const types = (output.match(/^(?:export\s+)?(?:interface|type)\s+/gm) ?? []).length;
  const annotations = (output.match(/:\s*(?:string|number|boolean|unknown|Record<|Promise<|Array<|\w+\[\])/g) ?? []).length;
  console.log(`${OUTPUT}: ${output.split("\n").length} lines, ${types} type declarations, ${annotations} annotations`);
}

await main();