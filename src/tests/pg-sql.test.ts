import { describe, expect, test } from "bun:test";
import { translate } from "../state/pg-sql.mjs";

describe("SQLite to PostgreSQL translation", () => {
  test("numbers placeholders outside string literals and comments", () => {
    expect(translate("SELECT * FROM messages WHERE id=? AND text='a?b' AND room_id=? -- ?\n"))
      .toBe("SELECT * FROM messages WHERE id=$1 AND text='a?b' AND room_id=$2 -- ?");
  });

  test("maps 64-bit integers and AUTOINCREMENT identity", () => {
    expect(translate("CREATE TABLE messages(seq INTEGER PRIMARY KEY AUTOINCREMENT,created_at INTEGER NOT NULL)"))
      .toBe("CREATE TABLE messages(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,created_at BIGINT NOT NULL)");
  });

  test("turns INSERT OR IGNORE into ON CONFLICT DO NOTHING", () => {
    expect(translate("INSERT OR IGNORE INTO messages(id,text) VALUES(?,?)"))
      .toBe("INSERT INTO messages(id,text) VALUES($1,$2) ON CONFLICT DO NOTHING");
  });

  test("strips pragmas and translates PRAGMA table_info", () => {
    expect(translate("PRAGMA busy_timeout=5000; PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON;")).toBe("");
    const info = translate("PRAGMA table_info(messages)");
    expect(info).toContain("information_schema.columns");
    expect(info).toContain("table_name='messages'");
    expect(info).toContain("AS name");
  });

  test("quotes camelCase aliases but leaves DEFAULT AS IDENTITY alone", () => {
    const sql = translate("SELECT room_id AS roomID,created_at AS createdAt,id FROM resources");
    expect(sql).toContain('AS "roomID"');
    expect(sql).toContain('AS "createdAt"');
    expect(translate("CREATE TABLE t(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)"))
      .toBe("CREATE TABLE t(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
  });

  test("uses GREATEST/LEAST for scalar max/min and leaves aggregates", () => {
    expect(translate("UPDATE registry SET last_read_ts=max(coalesce(last_read_ts,0),?)"))
      .toBe("UPDATE registry SET last_read_ts=GREATEST(coalesce(last_read_ts,0),$1)");
    expect(translate("SELECT max(coalesce(a,0),b) FROM t")).toBe("SELECT GREATEST(coalesce(a,0),b) FROM t");
    expect(translate("SELECT max(seq) FROM messages")).toBe("SELECT max(seq) FROM messages");
  });

  test("casts untyped CASE and IS NULL parameters", () => {
    expect(translate("SELECT CASE WHEN ? THEN 1 ELSE 0 END")).toBe("SELECT CASE WHEN $1::boolean THEN 1 ELSE 0 END");
    expect(translate("SELECT * FROM messages WHERE (? IS NULL OR room_id=?)"))
      .toBe("SELECT * FROM messages WHERE ($1::text IS NULL OR room_id=$2)");
  });

  test("normalizes manual BEGIN IMMEDIATE", () => {
    expect(translate("BEGIN IMMEDIATE; CREATE TABLE IF NOT EXISTS t(a INTEGER); COMMIT"))
      .toBe("BEGIN; CREATE TABLE IF NOT EXISTS t(a BIGINT); COMMIT");
  });
});